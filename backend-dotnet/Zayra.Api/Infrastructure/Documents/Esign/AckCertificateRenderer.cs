using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using Zayra.Api.Application.Esign;
using Zayra.Api.Infrastructure.Documents.Letters;

namespace Zayra.Api.Infrastructure.Documents.Esign;

public sealed record AckCertificateData(
    string CompanyName, string EmployeeName, string EmployeeCode, string DocumentTitle, string DocumentFileName, string DocumentSha256,
    string TypedName, DateTime SignedAtUtc, string Method, string? WitnessName, string ConsentVersion, string ConsentTextEn, string ConsentTextAr,
    string RecordHash, string VerificationCode);

/// <summary>
/// The bilingual (EN/AR) evidence page for one acknowledgement. It is generated by the server from the stored record only;
/// nothing on it comes from the browser except the typed name, which was matched against the employee record first.
/// It states plainly that this is an electronic acknowledgement and not a qualified electronic signature (CD13/CD50).
/// </summary>
public static class AckCertificateRenderer
{
    public const string StatementEn = "Electronic acknowledgement - this is not a qualified electronic signature.";
    public const string StatementAr = "إقرار إلكتروني - وهذا ليس توقيعاً إلكترونياً مؤهلاً.";
    public const string TitleEn = "Certificate of electronic acknowledgement";
    public const string TitleAr = "شهادة إقرار إلكتروني";

    public static byte[] Render(AckCertificateData d)
    {
        DocumentFonts.EnsureRegistered();
        var signedAt = SignatureChain.ToMicroseconds(d.SignedAtUtc).ToString("yyyy-MM-dd HH:mm:ss 'UTC'", System.Globalization.CultureInfo.InvariantCulture);
        var method = d.Method == EsignConstants.MethodHrDevice ? "On HR device, employee authenticated / على جهاز الموارد البشرية بمصادقة الموظف" : "Employee self-service / الخدمة الذاتية للموظف";
        var rows = new List<(string En, string Ar, string Value)>
        {
            ("Employee", "الموظف", $"{d.EmployeeName} ({d.EmployeeCode})"),
            ("Company", "الشركة", d.CompanyName),
            ("Document", "المستند", $"{d.DocumentTitle} - {d.DocumentFileName}"),
            ("Name typed by the signer", "الاسم المكتوب", d.TypedName),
            ("Acknowledged at", "وقت الإقرار", signedAt),
            ("Method", "الطريقة", method),
        };
        if (!string.IsNullOrWhiteSpace(d.WitnessName)) rows.Add(("Present on the HR device", "الموظف المرافق", d.WitnessName!));
        rows.Add(("Consent text version", "إصدار نص الإقرار", d.ConsentVersion));

        var doc = Document.Create(container => container.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(40);
            page.DefaultTextStyle(s => s.FontSize(10).FontColor(Colors.Grey.Darken3).FontFamily(DocumentFonts.LatinFamily, DocumentFonts.ArabicFamily));
            page.Header().Column(col =>
            {
                col.Item().Text(d.CompanyName).FontSize(13).Bold();
                col.Item().PaddingTop(4).Text(TitleEn).FontSize(15).SemiBold();
                col.Item().ContentFromRightToLeft().Text(TitleAr).FontSize(15).SemiBold().DirectionFromRightToLeft();
                col.Item().PaddingVertical(6).LineHorizontal(1).LineColor(Colors.Grey.Medium);
            });
            page.Content().Column(col =>
            {
                col.Spacing(5);
                foreach (var (en, ar, value) in rows)
                {
                    col.Item().Row(r =>
                    {
                        r.ConstantItem(170).Text(en).SemiBold();
                        r.RelativeItem().Text(value);
                        r.ConstantItem(90).AlignRight().Text(ar).FontColor(Colors.Grey.Darken1);
                    });
                }
                col.Item().PaddingTop(8).Text("Document SHA-256").SemiBold();
                col.Item().Text(d.DocumentSha256).FontSize(8.5f);
                col.Item().PaddingTop(4).Text("Record hash").SemiBold();
                col.Item().Text(d.RecordHash).FontSize(8.5f);
                col.Item().PaddingTop(4).Text($"Verification code: {d.VerificationCode}").FontSize(12).Bold();
                col.Item().PaddingTop(10).Text("What was acknowledged").SemiBold();
                col.Item().Text(d.ConsentTextEn);
                col.Item().PaddingTop(4).ContentFromRightToLeft().Text(d.ConsentTextAr).DirectionFromRightToLeft();
                col.Item().PaddingTop(12).Background(Colors.Grey.Lighten4).Padding(8).Column(c =>
                {
                    c.Item().Text(StatementEn).SemiBold();
                    c.Item().ContentFromRightToLeft().Text(StatementAr).SemiBold().DirectionFromRightToLeft();
                });
            });
            page.Footer().AlignCenter().Text("KynexOne - the record can be re-checked by an authorised user from the employee's Signatures tab.").FontSize(7).FontColor(Colors.Grey.Medium);
        }));
        return doc.GeneratePdf();
    }
}
